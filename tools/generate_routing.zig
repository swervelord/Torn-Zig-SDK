const std = @import("std");

/// Copies maintained routing contracts into an offline Zig module. No network.
pub fn main(init: std.process.Init) !void {
    const a = init.arena.allocator();
    const io = init.io;
    const dir = std.Io.Dir.cwd();
    const args = try init.minimal.args.toSlice(a);
    const check = args.len > 1 and std.mem.eql(u8, args[1], "--check");
    // Embedded inputs are normalized to LF so output never depends on checkout newline settings.
    const manifest = try readLf(a, io, "spec/routing-manifest.json", 8 * 1024 * 1024);
    const v1 = try readLf(a, io, "spec/v1-catalog.json", 1024 * 1024);
    const overrides = try dir.readFileAlloc(io, "spec/routing-overrides.json", a, .limited(1024 * 1024));
    const parsed = try std.json.parseFromSlice(std.json.Value, a, manifest, .{});
    const overrides_parsed = try std.json.parseFromSlice(std.json.Value, a, overrides, .{});
    var output: std.Io.Writer.Allocating = .init(a);
    const w = &output.writer;
    try w.writeAll("// Generated by tools/generate_routing.zig. Do not edit.\n");
    try w.print("pub const manifest_json = \"{f}\";\n", .{std.zig.fmtString(manifest)});
    try w.print("pub const v1_json = \"{f}\";\n", .{std.zig.fmtString(v1)});
    try w.writeAll("pub const V1Entry = struct { resource: []const u8, name: []const u8 };\npub const v1_catalog = [_]V1Entry{\n");
    for (parsed.value.object.get("v1_catalog").?.array.items) |entry| {
        try w.print("    .{{ .resource = \"{f}\", .name = \"{f}\" }},\n", .{ std.zig.fmtString(entry.object.get("resource").?.string), std.zig.fmtString(entry.object.get("name").?.string) });
    }
    try w.writeAll("};\n");
    try w.writeAll("pub const IdDomain = struct { resource: []const u8, selection: []const u8, name: []const u8, parameter: []const u8, query: bool };\npub const id_domains = [_]IdDomain{\n");
    if (overrides_parsed.value.object.get("id_domains")) |domains| {
        var domain_it = domains.object.iterator();
        while (domain_it.next()) |entry| {
            const slash = std.mem.indexOfScalar(u8, entry.key_ptr.*, '/').?;
            const v = entry.value_ptr.*;
            try w.print("    .{{ .resource=\"{f}\", .selection=\"{f}\", .name=\"{f}\", .parameter=\"{f}\", .query={s} }},\n", .{ std.zig.fmtString(entry.key_ptr.*[0..slash]), std.zig.fmtString(entry.key_ptr.*[slash + 1 ..]), std.zig.fmtString(v.object.get("domain").?.string), std.zig.fmtString(v.object.get("parameter").?.string), if (v.object.get("query").?.bool) "true" else "false" });
        }
    }
    try w.writeAll("};\npub const force_direct = [_][]const u8{\n");
    if (overrides_parsed.value.object.get("force_direct")) |entries| for (entries.array.items) |entry| try w.print("    \"{f}\",\n", .{std.zig.fmtString(entry.string)});
    try w.writeAll("};\n");
    const official_bytes = try dir.readFileAlloc(io, "spec/openapi-6.15.0.json", a, .limited(8 * 1024 * 1024));
    const official = try std.json.parseFromSlice(std.json.Value, a, official_bytes, .{});
    try w.writeAll("pub const RequiredQuery = struct { resource: []const u8, selection: []const u8, parameter: []const u8, required: bool, choices: []const []const u8 };\npub const required_queries = [_]RequiredQuery{\n");
    var path_it = official.value.object.get("paths").?.object.iterator();
    while (path_it.next()) |path_entry| {
        var parts = std.mem.tokenizeScalar(u8, path_entry.key_ptr.*, '/');
        const resource = parts.next().?;
        if (parts.next() == null) continue;
        const last_slash = std.mem.lastIndexOfScalar(u8, path_entry.key_ptr.*, '/').?;
        const selection = try std.ascii.allocLowerString(a, path_entry.key_ptr.*[last_slash + 1 ..]);
        const op = path_entry.value_ptr.object.get("get") orelse continue;
        const params = op.object.get("parameters") orelse continue;
        for (params.array.items) |p| {
            const resolved = if (p.object.get("$ref")) |r| official.value.object.get("components").?.object.get("parameters").?.object.get(r.string[24..]).? else p;
            if (!std.mem.eql(u8, resolved.object.get("in").?.string, "query")) continue;
            const required_value = resolved.object.get("required");
            const required = if (required_value) |v| v.bool else false;
            const parameter = resolved.object.get("name").?.string;
            if (std.mem.eql(u8, parameter, "key")) continue;
            var schema = resolved.object.get("schema").?;
            if (schema.object.get("$ref")) |r| schema = official.value.object.get("components").?.object.get("schemas").?.object.get(r.string[21..]).?;
            if (!required and schema.object.get("enum") == null) continue;
            try w.print("    .{{ .resource = \"{f}\", .selection = \"{f}\", .parameter = \"{f}\", .required={s}, .choices = &.{{", .{ std.zig.fmtString(resource), std.zig.fmtString(selection), std.zig.fmtString(parameter), if (required) "true" else "false" });
            if (schema.object.get("enum")) |choices| for (choices.array.items) |choice| try w.print("\"{f}\",", .{std.zig.fmtString(choice.string)});
            try w.writeAll("} },\n");
        }
    }
    try w.writeAll("};\n");
    try save(a, io, "src/generated/routing.zig", try output.toOwnedSlice(), check);
    var selections: std.Io.Writer.Allocating = .init(a);
    const s = &selections.writer;
    try s.writeAll("// Generated by tools/generate_routing.zig. Do not edit.\nconst planner = @import(\"../planner.zig\");\nconst current = @import(\"current.zig\");\nconst compatibility = @import(\"compatibility.zig\");\nconst model = @import(\"../model.zig\");\n");
    const resources = [_][]const u8{ "user", "faction", "company", "forum", "key", "market", "property", "racing", "torn" };
    const caps = parsed.value.object.get("capabilities").?.array.items;
    const compat = overrides_parsed.value.object.get("compatibility_types").?;
    for (resources) |resource| {
        try s.print("pub const {s} = struct {{\n", .{resource});
        for (caps) |cap| {
            const obj = cap.object;
            if (!std.mem.eql(u8, obj.get("resource").?.string, resource)) continue;
            const name = obj.get("name").?.string;
            const csv = obj.get("csv").?.bool;
            const ev = obj.get("endpoints").?;
            const endpoints: []const std.json.Value = if (ev == .array) ev.array.items else &.{};
            const key = try std.fmt.allocPrint(a, "{s}/{s}", .{ resource, name });
            const override = compat.object.get(key);
            try s.print("    pub const @\"{f}\" = struct {{\n        pub const resource = planner.Resource.{s};\n        pub const name = \"{f}\";\n", .{ std.zig.fmtString(name), resource, std.zig.fmtString(name) });
            if (csv) {
                try s.writeAll("        pub const Response = []const u8;\n");
            } else if (override) |value| {
                try s.print("        pub const Response = compatibility.@\"{f}\";\n", .{std.zig.fmtString(value.string)});
            } else if (endpoints.len > 0 and endpoints[0].object.get("schema").?.string.len > 0) {
                try s.print("        pub const Response = current.@\"{f}\";\n", .{std.zig.fmtString(endpoints[0].object.get("schema").?.string)});
            } else {
                try s.writeAll("        pub const Response = model.RawValue;\n");
            }
            try s.writeAll("    };\n");
        }
        if (std.mem.eql(u8, resource, "company")) try s.writeAll("    pub const detail = struct { pub const resource = planner.Resource.company; pub const name = \"profile\"; pub const required_target = \"id\"; pub const Response = compatibility.CompanyDetailedBundle; };\n");
        if (std.mem.eql(u8, resource, "torn")) try s.writeAll("    pub const stock = struct { pub const resource = planner.Resource.torn; pub const name = \"stocks\"; pub const required_target = \"stockId\"; pub const force_direct = true; pub const Response = compatibility.TornStockBundle; };\n");
        try s.writeAll("};\n");
    }
    try save(a, io, "src/generated/selections.zig", try selections.toOwnedSlice(), check);
    var coverage: std.Io.Writer.Allocating = .init(a);
    const cw = &coverage.writer;
    try cw.writeAll("{\n  \"source\": \"spec/routing-manifest.json and routing-overrides.json\",\n  \"evidence\": \"Official v2 response associations plus explicitly maintained compatibility overrides. v1 catalog membership is not an authoritative v1 payload specification.\",\n  \"typed_helpers\": 210,\n  \"raw_helpers\": 205,\n  \"csv_helpers\": 3,\n  \"v1_entries\": 184,\n  \"helpers\": [\n");
    for (caps, 0..) |cap, i| {
        const obj = cap.object;
        const resource = obj.get("resource").?.string;
        const name = obj.get("name").?.string;
        const csv = obj.get("csv").?.bool;
        const ev = obj.get("endpoints").?;
        const endpoints: []const std.json.Value = if (ev == .array) ev.array.items else &.{};
        const key = try std.fmt.allocPrint(a, "{s}/{s}", .{ resource, name });
        const response = if (csv) "[]const u8" else if (compat.object.get(key)) |ov| try std.fmt.allocPrint(a, "compatibility.{s}", .{ov.string}) else if (endpoints.len > 0) try std.fmt.allocPrint(a, "current.{s}", .{endpoints[0].object.get("schema").?.string}) else "model.RawValue";
        try cw.print("    {{\"resource\":\"{s}\",\"selection\":\"{s}\",\"token\":\"selections.{s}.{s}\",\"typed_api\":\"Client.select(selections.{s}.{s}, target, filters, options)\",\"result\":\"{s}\",\"csv\":{s},\"raw_api\":", .{ resource, name, resource, name, resource, name, response, if (csv) "true" else "false" });
        if (csv) try cw.writeAll("null") else try cw.print("\"Client.raw(selections.{s}.{s}, target, filters, options)\"", .{ resource, name });
        try cw.print("}}{s}\n", .{if (i + 1 < caps.len) "," else ""});
    }
    try cw.writeAll("  ],\n  \"aliases\": [\n    {\"token\":\"selections.company.detail\",\"selection\":\"profile\",\"required_target\":\"id\",\"result\":\"compatibility.CompanyDetailedBundle\"},\n    {\"token\":\"selections.torn.stock\",\"selection\":\"stocks\",\"required_target\":\"stockId\",\"exact_path\":\"/torn/{stockId}/stocks\",\"result\":\"compatibility.TornStockBundle\"}\n  ],\n  \"v1_catalog\": [\n");
    const v1entries = parsed.value.object.get("v1_catalog").?.array.items;
    for (v1entries, 0..) |entry, i| {
        try cw.print("    {{\"resource\":\"{s}\",\"selection\":\"{s}\",\"public_api\":\"planner.build(allocator, Input with mode=v1)\",\"membership_api\":\"planner.v1Contains\",\"result\":\"model.RawValue\"}}{s}\n", .{ entry.object.get("resource").?.string, entry.object.get("name").?.string, if (i + 1 < v1entries.len) "," else "" });
    }
    try cw.writeAll("  ],\n  \"reviewed_routing_overrides\": ");
    try std.json.Stringify.value(overrides_parsed.value, .{ .whitespace = .indent_2 }, cw);
    try cw.writeAll("\n}\n");
    try saveBytes(a, io, "docs/routing-coverage.json", try coverage.toOwnedSlice(), check);
}

fn save(a: std.mem.Allocator, io: std.Io, path: []const u8, source: []const u8, check: bool) !void {
    const z = try a.dupeSentinel(u8, source, 0);
    var ast = try std.zig.Ast.parse(a, z, .{});
    defer ast.deinit(a);
    if (ast.errors.len > 0) return error.InvalidGeneratedZig;
    var formatted: std.Io.Writer.Allocating = .init(a);
    try ast.render(a, &formatted.writer, .{});
    const result = try formatted.toOwnedSlice();
    try saveBytes(a, io, path, result, check);
}

fn saveBytes(a: std.mem.Allocator, io: std.Io, path: []const u8, result: []const u8, check: bool) !void {
    const dir = std.Io.Dir.cwd();
    if (check) {
        const existing = try dir.readFileAlloc(io, path, a, .limited(16 * 1024 * 1024));
        if (!std.mem.eql(u8, result, existing)) return error.StaleRouting;
    } else {
        try dir.writeFile(io, .{ .sub_path = path, .data = result });
    }
}

fn readLf(a: std.mem.Allocator, io: std.Io, path: []const u8, limit: usize) ![]u8 {
    const bytes = try std.Io.Dir.cwd().readFileAlloc(io, path, a, .limited(limit));
    var out: std.ArrayList(u8) = try .initCapacity(a, bytes.len);
    var i: usize = 0;
    while (i < bytes.len) : (i += 1) {
        if (bytes[i] == '\r' and i + 1 < bytes.len and bytes[i + 1] == '\n') continue;
        out.appendAssumeCapacity(bytes[i]);
    }
    return out.items;
}
